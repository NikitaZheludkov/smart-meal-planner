const FRY_PER_PORTION = 10 // мл, если для блюда нет своего количества
const BAKE_SPRAY = 5 // мл на всё блюдо — распылитель

const results = []
for (const d of data.dishes) {
  const tot = [0, 0, 0, 0]
  const notes = []
  const add = (name, amount, unit) => {
    const v = P[name]
    if (!v) { notes.push('НЕТ ДАННЫХ: ' + name); return }
    const u = (unit || '').toLowerCase()
    const grams = (u === 'шт' || u === 'упак' || u === 'кг') ? amount * (v[4] || (u === 'кг' ? 1000 : NaN)) : amount
    if (Number.isNaN(grams)) { notes.push('НЕТ ВЕСА ШТ: ' + name); return }
    for (let i = 0; i < 4; i++) tot[i] += v[i] * grams / 100
  }
  for (const [name, amount, unit] of d.ings) add(name, amount, unit)
  const hasOil = d.ings.some(([n]) => /^(масло (подсолнечное|оливковое|кунжутное)|сливочное масло)/i.test(n))
  let hidden = HIDDEN[d.name] || []
  if (d.method === 'fry') {
    // своё количество (в т.ч. пустое — «на сухой сковороде») важнее нормы
    if (!(d.name in HIDDEN) && !hasOil) hidden = [...hidden, [OIL, FRY_PER_PORTION * (d.yield || 1)]]
  } else if (d.method === 'bake') {
    // обжарка перед запеканием (фарш) остаётся; плюс распылитель на форму
    if (!hasOil) hidden = [...hidden, [OIL + ' ', BAKE_SPRAY]]
  } else if (d.name !== 'Овощной салат') {
    hidden = hidden.filter(([n]) => n !== OIL) // варить/без готовки — без масла для жарки
  }
  for (const [name, amount] of hidden) add(name.trim(), amount, 'г')
  const per = tot.map((x) => Math.round(x / (d.yield || 1)))
  results.push({ name: d.name, method: d.method, yield: d.yield, old: d.kbju, now: per, hidden: hidden.map(([n, a]) => `${n.replace('Масло подсолнечное', 'масло')} ${a}`).join(', '), notes })
}
results.sort((a, b) => a.name.localeCompare(b.name, 'ru'))
if (process.argv.includes('--json')) {
  console.log(JSON.stringify(Object.fromEntries(results.map((r) => [r.name, r.now]))))
  process.exit(0)
}
for (const r of results) {
  const diff = r.old[0] ? r.now[0] - r.old[0] : null
  console.log(`${r.name} | ${r.method} | ${r.yield} | было ${r.old.join('/')} | стало ${r.now.join('/')} | ${diff === null ? 'НОВОЕ' : (diff > 0 ? '+' : '') + diff} | ${r.hidden} ${r.notes.join('; ')}`)
}
