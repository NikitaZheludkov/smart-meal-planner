c = sqlite3.connect(DB)
rows = []
missing = set()
for did, name, by, k0, p0, f0, c0 in c.execute(
        'select id, trim(name), batch_yield, kcal, protein, fat, carbs from dishes where household=? order by name', (H,)).fetchall():
    tot = [0.0, 0.0, 0.0, 0.0]
    for amt, pname, unit in c.execute(
            'select i.amount, trim(p.name), p.unit from ingredients i join products p on p.id=i.product where i.dish=?', (did,)):
        v = P.get(pname)
        if not v:
            missing.add(pname); continue
        grams = amt * v[4] if unit in ('Шт', 'Упак') and v[4] else amt
        if unit in ('Шт', 'Упак') and not v[4]:
            missing.add(f'{pname} ({unit})')
        for i in range(4):
            tot[i] += v[i] * grams / 100
    for pname, grams, _why in HIDDEN.get(name, []):
        v = P[pname]
        for i in range(4):
            tot[i] += v[i] * grams / 100
    portions = by or 1
    new = [round(x / portions) for x in tot]
    rows.append((did, name, (k0, p0, f0, c0), new))

if missing:
    print('НЕТ ДАННЫХ:', ', '.join(sorted(missing)))
for _, name, old, new in rows:
    extra = ', '.join(f'{p.lower()} {g}' for p, g, _ in HIDDEN.get(name, []))
    print(f'{name}: {old[0]}/{old[1]}/{old[2]}/{old[3]} -> {new[0]}/{new[1]}/{new[2]}/{new[3]}' + (f'  [+ {extra}]' if extra else ''))

